from gen_seed_configurations import baseline_lines
from gen_seed_fixture import T, FixtureNames, fixture_body

# The fixture's ids are kept so the demonstration tenant's figures equal the
# local fixture's; the pilot's id is minted fresh, so it never shares one
# (U92). driver_subject is off so none of the fixture's people can sign in.
DEMO = FixtureNames(
    branding=None,
    registrations={1: "DEM001GP", 2: "DEM002GP", 3: "DEM003GP"},
    code_fleet="DEM",
    comment="Demonstration inspection. The readings are specification data, not a finding about any vehicle.",
    defect_report="Demonstration defect report.",
    driver_subject=False,
)


def demo_sql():
    L = [
        "-- Demonstration tenant (OR-TRN-003, U92): the Appendix E and J fixture",
        "-- under names that are not the pilot's, with every number kept. Staging",
        "-- only (U116), never production, because it holds specification data",
        "-- under the fixture's ids. Generated by gen_seed_demo.py; do not hand-edit.",
        "-- docs/runbooks/provision-a-tenant.md says how to load it.",
        "\\set ON_ERROR_STOP on",
        "SET client_encoding = 'UTF8';",
        "SET search_path = app, public;",
        "BEGIN;",
        # tenant_self's WITH CHECK refuses the tenant row unless its id is
        # bound first, under a role that does not bypass RLS (rule 1).
        f"SELECT set_config('app.tenant_id', '{T}', true);",
        f"INSERT INTO app.tenant (id,name,subdomain,state,display_code_policy) VALUES ('{T}','Demonstration Fleet','demo','ACTIVE','GENERATED');",
        "-- Loading it ACTIVE is its activation, so the horizon is the load date",
        "-- where the fleet is (FR-TEN-021), and the fixture's readings sit behind",
        "-- it as imported history would.",
        f"UPDATE app.tenant SET history_horizon = app.tenant_today(timezone) WHERE id = '{T}';",
        f"INSERT INTO app.display_code_counter (tenant_id,prefix) VALUES ('{T}','DEMO');",
        "",
    ]
    L.extend(baseline_lines(T))
    L.extend(fixture_body(DEMO, others=False))
    L.append("COMMIT;")
    return "\n".join(L) + "\n"


def main():
    with open("demo_tenant.sql", "w", encoding="utf-8", newline="\n") as f:
        f.write(demo_sql())
    print("demonstration tenant written")


if __name__ == "__main__":
    main()
